def check_referenced_media_exist(objects, previews_dir="extraction/previews"):
	import os
	missing = []
	for o in objects:
		for m in o.get("media", []):
			if not os.path.exists(os.path.join(previews_dir, m)):
				missing.append((o["id"], m))
	return missing


