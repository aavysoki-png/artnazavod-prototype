/**
 * Год как число для сортировки/группировки — берёт первые 4 цифры из
 * `year` (у диапазонов вида «2022/2026» это 2022). `null` остаётся
 * `null`.
 */
export function yearOf(object: ArtObject): number | null {
	if (!object.year) return null;
	const match = object.year.match(/\d{4}/);
	return match ? Number(match[0]) : null;
}

const KNOWN_YEARS = ART_OBJECTS.map(yearOf).filter((y): y is number => y !== null);
