/**
 * Год как число для сортировки/группировки — берёт первые 4 цифры из
 * `year` (у «декабрь 2025» это 2025). `null` остаётся `null` — не
 * подставляем правдоподобный год туда, где заказчик его не дал.
 */
export function yearOf(object: ArtObject): number | null {
	if (!object.year) return null;
	const match = object.year.match(/\d{4}/);
	return match ? Number(match[0]) : null;
}

// Реальный диапазон по данным реестра: min/max среди объектов с указанным
// годом (2022 … 2026 — «Сотворчество», «Точка синергии» и другие 2026-е
// объекты уже в реестре, диапазон не «2022–2025», это было бы неточно).
const KNOWN_YEARS = ART_OBJECTS.map(yearOf).filter((y): y is number => y !== null);
export const YEARS_LABEL = `${Math.min(...KNOWN_YEARS)}–${Math.max(...KNOWN_YEARS)}`;

/** Порядковый номер объекта среди объектов той же площадки — для того, чтобы
 * соседние объекты одной площадки показывали разные фото из общего пула
 * (см. `data/photos.ts`), а не один и тот же кадр. */
const FACILITY_INDEX = new Map<string, number>();
export const FACILITY_INDEX_BY_SLUG: Readonly<Record<string, number>> = (() => {
	const out: Record<string, number> = {};
	for (const object of ART_OBJECTS) {
		const next = (FACILITY_INDEX.get(object.facility) ?? 0) + 1;
		FACILITY_INDEX.set(object.facility, next);
		out[object.slug] = next - 1;
	}
	return out;
})();
